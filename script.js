/* FILTROS PROYECTOS */
const filterBtns = document.querySelectorAll('.filter-tabs button');
const projectCards = document.querySelectorAll('.projects-grid .project-card');
filterBtns.forEach(btn => {
    btn.addEventListener('click', () => {
        filterBtns.forEach(b => b.classList.remove('active'));
        btn.classList.add('active');
        const filter = btn.getAttribute('data-filter');
        projectCards.forEach(card => {
            const categories = (card.getAttribute('data-category') || '').split(' ');
            if (filter === 'all' || categories.includes(filter)) {
                card.classList.remove('hidden');
                gsap.fromTo(card, { opacity: 0, scale: 0.95 }, { opacity: 1, scale: 1, duration: 0.4 });
            } else {
                card.classList.add('hidden');
            }
        });
    });
});

/* NAV SCROLL */
const navLinks = document.querySelectorAll('.nav-link, .header-nav a');
navLinks.forEach(link => {
    link.addEventListener('click', function(e) {
        e.preventDefault();
        const target = this.getAttribute('href');
        navLinks.forEach(l => l.classList.remove('active'));
        document.querySelectorAll(`a[href="${target}"]`).forEach(l => l.classList.add('active'));
        if (target && target !== '#') {
            const el = document.querySelector(target);
            if (el) lenis.scrollTo(el, { offset: -20 });
        }
    });
});

const sections = document.querySelectorAll('section[id]');
window.addEventListener('scroll', () => {
    const scrollY = window.scrollY + window.innerHeight / 2;
    sections.forEach(sec => {
        const top = sec.offsetTop;
        const bottom = top + sec.offsetHeight;
        if (scrollY >= top && scrollY < bottom) {
            navLinks.forEach(l => l.classList.remove('active'));
            document.querySelectorAll(`a[href="#${sec.id}"]`).forEach(l => l.classList.add('active'));
        }
    });
});